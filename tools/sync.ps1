<#
.SYNOPSIS
    Generates the Codex and Antigravity widgets from the Claude one, then checks every script.
.DESCRIPTION
    The widgets share one codebase: claude-usage-widget\ is the source. Everything in the Codex and Antigravity
    copies except their "# >>> product" block is generated from it. Their installers, uninstallers and watchdogs
    are generated by renaming Claude to Codex / Antigravity. Each collector (codex-usage.ps1,
    antigravity-usage.ps1) is its own hand-written file.
    Every .ps1 file must be UTF-8 with BOM: Windows PowerShell 5.1 misreads non-ASCII text without it.
    -Check changes nothing and fails if any generated file is out of date (CI runs it).
#>
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root   = Split-Path -Parent $PSScriptRoot
$claude = Join-Path $root 'claude-usage-widget'
$bom    = New-Object Text.UTF8Encoding($true)

$products = @(
    @{ Key = 'codex'; Name = 'Codex'; Block = @'
# >>> product (everything else in this file is identical in every widget)
$script:ProductKey    = 'codex'
$script:ProductName   = 'Codex'
$script:AppName       = 'CodexUsageWidget'
$script:CollectorName = 'codex-usage.ps1'
$script:UsageUrl      = 'https://chatgpt.com/codex/settings/usage'
$script:WindowTitle   = 'Codex usage'
$script:AnchorTitle   = 'Claude usage'   # sits immediately left of the Claude pill when that one is visible
$script:DefaultPollSeconds = 60
$script:Accent        = '#6E7BF2' # product accent (card mark, pill dot, menu checks)
$script:MarkText      = '>_'
# <<< product
'@ },
    @{ Key = 'antigravity'; Name = 'Antigravity'; Block = @'
# >>> product (everything else in this file is identical in every widget)
$script:ProductKey    = 'antigravity'
$script:ProductName   = 'Antigravity'
$script:AppName       = 'AntigravityUsageWidget'
$script:CollectorName = 'antigravity-usage.ps1'
$script:UsageUrl      = 'https://antigravity.google/docs/plans'   # no web usage page: its plans and limits page
$script:WindowTitle   = 'Antigravity usage'
$script:AnchorTitle   = @('Codex usage', 'Claude usage')   # left of the Codex pill, else of the Claude pill
$script:DefaultPollSeconds = 60   # a local language server: no rate limit
$script:Accent        = '#3FB68B' # product accent (card mark, pill dot, menu checks)
$script:MarkText      = 'A'
# <<< product
'@ }
)

$wanted = [ordered]@{}
$src = [IO.File]::ReadAllText((Join-Path $claude 'claude-usage-widget.ps1'))
# The shared top strip (shared\WidgetStrip.cs, the same file in every Solarity widget repo) is embedded in the
# widget so the install stays one script: regenerate the block between its markers from the .cs file.
$cs = [IO.File]::ReadAllText((Join-Path $root 'shared\WidgetStrip.cs')).Replace("`r`n", "`n").TrimEnd("`n")
if ($cs -match "(?m)^'@") { throw "shared\WidgetStrip.cs has a line starting with '@, which would end the here-string" }
$stripRe = [regex]'(?s)    # >>> WidgetStrip\.cs[^
]*
.*?    # <<< WidgetStrip\.cs'
if (-not $stripRe.IsMatch($src)) { throw 'WidgetStrip.cs block not found in claude-usage-widget.ps1' }
$stripBlock = "    # >>> WidgetStrip.cs (generated from shared\WidgetStrip.cs by tools\sync.ps1: edit it there)`n" +
    "    if (-not ('SolarityWidgets.Strip' -as [type])) {`n        Add-Type -TypeDefinition @'`n" + $cs + "`n'@`n    }`n    # <<< WidgetStrip.cs"
$src = $stripRe.Replace($src, $stripBlock.Replace('$', '$$'), 1)
$wanted[(Join-Path $claude 'claude-usage-widget.ps1')] = $src
$re = [regex]'(?s)# >>> product.*?# <<< product'
if (-not $re.IsMatch($src)) { throw 'product block not found in claude-usage-widget.ps1' }
foreach ($p in $products) {
    $dir = Join-Path $root "$($p.Key)-usage-widget"
    $w = $re.Replace($src, $p.Block.Replace('$', '$$'), 1)
    $wanted[(Join-Path $dir "$($p.Key)-usage-widget.ps1")] = $w.Replace('    Claude usage taskbar widget (Windows PowerShell 5.1 + WPF).', "    $($p.Name) usage taskbar widget (Windows PowerShell 5.1 + WPF).")
    foreach ($f in 'install.ps1', 'uninstall.ps1', 'watchdog.ps1') {
        $s = [IO.File]::ReadAllText((Join-Path $claude $f))
        $wanted[(Join-Path $dir $f)] = $s -creplace 'Claude', $p.Name -creplace 'claude', $p.Key -creplace 'CLAUDE', $p.Key.ToUpperInvariant()
    }
}

$stale = @()
foreach ($path in $wanted.Keys) {
    $current = $(if (Test-Path -LiteralPath $path) { [IO.File]::ReadAllText($path) } else { $null })
    if ($current -cne $wanted[$path]) {   # -cne: a case-only drift ("claude" vs "Claude") is drift too
        $rel = (Split-Path -Leaf (Split-Path -Parent $path)) + '\' + (Split-Path -Leaf $path)
        if ($Check) { $stale += $rel }
        else {
            $dir = Split-Path -Parent $path
            if (-not (Test-Path -LiteralPath $dir)) { [void](New-Item -ItemType Directory -Path $dir) }
            [IO.File]::WriteAllText($path, $wanted[$path], $bom); "generated $rel"
        }
    }
}

$failed = @()
foreach ($f in Get-ChildItem -Path $root -Recurse -Filter *.ps1) {
    $bytes = [IO.File]::ReadAllBytes($f.FullName)
    if (-not ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF)) {
        if ($Check) { $failed += "$($f.Name): no UTF-8 BOM" } else { [IO.File]::WriteAllText($f.FullName, [IO.File]::ReadAllText($f.FullName, [Text.Encoding]::UTF8), $bom); "BOM added: $($f.Name)" }
    }
    $t = $null; $e = $null
    [void][System.Management.Automation.Language.Parser]::ParseFile($f.FullName, [ref]$t, [ref]$e)
    foreach ($x in @($e)) { $failed += "$($f.Name) line $($x.Extent.StartLineNumber): $($x.Message)" }
}
if ($stale.Count -gt 0) { $failed += "out of date (run tools\sync.ps1): $($stale -join ', ')" }
if ($failed.Count -gt 0) { $failed | ForEach-Object { Write-Host "FAIL $_" }; exit 1 }
'All scripts parse, have a UTF-8 BOM, and the Codex and Antigravity copies are up to date.'

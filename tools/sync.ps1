<#
.SYNOPSIS
    Generates the Codex widget from the Claude one, then checks every script.
.DESCRIPTION
    The two widgets share one codebase: claude-usage-widget\ is the source. Everything in the Codex copy except
    its "# >>> product" block is generated from it. Its installer and uninstaller are generated by renaming
    Claude to Codex. Its collector (codex-usage.ps1) is its own file.
    Every .ps1 file must be UTF-8 with BOM: Windows PowerShell 5.1 misreads non-ASCII text without it.
    -Check changes nothing and fails if any generated file is out of date (CI runs it).
#>
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root   = Split-Path -Parent $PSScriptRoot
$claude = Join-Path $root 'claude-usage-widget'
$codex  = Join-Path $root 'codex-usage-widget'
$bom    = New-Object Text.UTF8Encoding($true)

$block = @'
# >>> product (everything else in this file is identical in both widgets)
$script:ProductKey    = 'codex'
$script:ProductName   = 'Codex'
$script:AppName       = 'CodexUsageWidget'
$script:CollectorName = 'codex-usage.ps1'
$script:UsageUrl      = 'https://chatgpt.com/codex/settings/usage'
$script:WindowTitle   = 'Codex usage'
$script:AnchorTitle   = 'Claude usage'   # sits immediately left of the Claude pill when that one is visible
$script:DefaultPollSeconds = 60
$script:Accent        = '#6E7BF2' # product accent (card mark, pill dot, menu checks)
$script:MarkText      = '>_'
# <<< product
'@

$wanted = [ordered]@{}
$src = [IO.File]::ReadAllText((Join-Path $claude 'claude-usage-widget.ps1'))
$re = [regex]'(?s)# >>> product.*?# <<< product'
if (-not $re.IsMatch($src)) { throw 'product block not found in claude-usage-widget.ps1' }
$w = $re.Replace($src, $block.Replace('$', '$$'), 1)
$wanted[(Join-Path $codex 'codex-usage-widget.ps1')] = $w.Replace('    Claude usage taskbar widget (Windows PowerShell 5.1 + WPF).', '    Codex usage taskbar widget (Windows PowerShell 5.1 + WPF).')
foreach ($f in 'install.ps1', 'uninstall.ps1') {
    $s = [IO.File]::ReadAllText((Join-Path $claude $f))
    $wanted[(Join-Path $codex $f)] = $s -creplace 'Claude', 'Codex' -creplace 'claude', 'codex' -creplace 'CLAUDE', 'CODEX'
}

$stale = @()
foreach ($path in $wanted.Keys) {
    $current = $(if (Test-Path -LiteralPath $path) { [IO.File]::ReadAllText($path) } else { $null })
    if ($current -ne $wanted[$path]) {
        if ($Check) { $stale += (Split-Path -Leaf $path) } else { [IO.File]::WriteAllText($path, $wanted[$path], $bom); "generated $(Split-Path -Leaf $path)" }
    }
}

$failed = @()
foreach ($f in Get-ChildItem -Path $root -Recurse -Filter *.ps1) {
    $bytes = [IO.File]::ReadAllBytes($f.FullName)
    if (-not ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF)) {
        if ($Check) { $failed += "$($f.Name): no UTF-8 BOM" } else { [IO.File]::WriteAllText($f.FullName, [IO.File]::ReadAllText($f.FullName, [Text.Encoding]::UTF8), $bom); "BOM added: $($f.Name)" }
    }
    $t = $null; $e = $null
    [void][System.Management.Automation.Language.Parser]::ParseFile($f.FullName, [ref]$t, [ref]$e)
    foreach ($x in @($e)) { $failed += "$($f.Name) line $($x.Extent.StartLineNumber): $($x.Message)" }
}
if ($stale.Count -gt 0) { $failed += "out of date (run tools\sync.ps1): $($stale -join ', ')" }
if ($failed.Count -gt 0) { $failed | ForEach-Object { Write-Host "FAIL $_" }; exit 1 }
'All scripts parse, have a UTF-8 BOM, and the Codex copy is up to date.'
